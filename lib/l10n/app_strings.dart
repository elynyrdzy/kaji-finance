  static String get(String key, String code) {
    final map = code == 'en' ? _en : _id;
    return map[key] ?? key;
  }

  /// Interpolasi `{name}` sederhana: tr('x', lang, {'name': v}).
  static String fill(String key, String code, [Map<String, Object>? args]) {
    var s = get(key, code);
    args?.forEach((k, v) {
      s = s.replaceAll('{$k}', '$v');
    });
    return s;
  }

